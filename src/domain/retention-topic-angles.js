export function createRetentionTopicAngle({ ecosystem, action, index = 0 } = {}) {
  const presets = ecosystemAnglePresets[ecosystem?.id] || fallbackAngles;
  const matched = presets.find((preset) => preset.match?.test(action || ""));
  const preset = matched || presets[index % presets.length] || fallbackAngles[index % fallbackAngles.length];
  return {
    ...preset,
    angleType: matched ? "specific-mechanism" : "retention-contrast",
    instruction: [
      "Начни с конкретного конфликта или механизма, а не с общей пользы.",
      "Хук должен быть понятен за 2 секунды и звучать как наблюдение из жизни.",
      "Не называй бренд в теме; продукт может быть только мягким мостом внутри сценария."
    ].join(" ")
  };
}
